#!/usr/bin/env bash
# Builds src/docs/supplemental-ui/js/vendor/highlight.js, which replaces the UI bundle's highlight.js on the website.
# The UI bundle's copy has no TypeScript or SCSS, and its "shell" language only highlights lines that start with a prompt.
# This uses highlight.js 9.x, like Antora's default UI, because later versions drop the callout markup in code blocks.
# The package is fetched with npm pack, so none of its install scripts run.
set -euo pipefail

version=9.18.5
languages=(asciidoc bash css diff dockerfile groovy java javascript json kotlin markdown plaintext properties python ruby scss sql typescript xml yaml)
root=$(cd "$(dirname "$0")/.." && pwd)
out=$root/src/docs/supplemental-ui/js/vendor/highlight.js
mkdir -p "$(dirname "$out")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

(cd "$tmp" && npm pack --silent "highlight.js@$version" > /dev/null && tar -xzf highlight.js-$version.tgz)
lib=$tmp/package/lib

{
  echo "/*! highlight.js $version | BSD-3-Clause | https://highlightjs.org/ | generated by scripts/build-highlight.sh */"
  cat "$lib/highlight.js"
  echo ';(function (hljs) {'
  echo '  var defs = {}'
  for lang in "${languages[@]}"; do
    echo "  defs['$lang'] = (function () { var module = {};"
    cat "$lib/languages/$lang.js"
    echo "  return module.exports })()"
    echo "  hljs.registerLanguage('$lang', defs['$lang'])"
  done
  cat <<'JS'
  // Most [source,shell] blocks are commands without a prompt, so highlight them as bash
  hljs.registerLanguage('shell', defs.bash)
  // Indented-syntax Sass reads fine with the SCSS rules
  hljs.registerLanguage('sass', defs.scss)
  hljs.registerLanguage('none', defs.plaintext)
  hljs.registerLanguage('text', defs.plaintext)
  hljs.registerLanguage('docker', defs.dockerfile)
  ;[].slice.call(document.querySelectorAll('pre code.hljs[data-lang]')).forEach(function (node) {
    hljs.highlightBlock(node)
  })
})(window.hljs)
JS
} > "$out"
echo "Wrote $out ($(wc -c < "$out" | tr -d ' ') bytes)"
